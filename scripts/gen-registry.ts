#!/usr/bin/env -S npx --yes tsx
// Package registries use only this explicit, local input list. Hosts generate
// their own resolved maps and pass them in; installed packages are immutable.
import {readFileSync, writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';

const root = new URL('../typescript/src/', import.meta.url);
const inputs = JSON.parse(readFileSync(new URL('./builtin-inputs.json', import.meta.url), 'utf8')) as {
  effects: string[];
  clipTypeAliases: Record<string, string>;
  animations: string[];
  transitions: string[];
  themes: {id: string; version: string; effects: string[]}[];
};
const json = (path: string) => JSON.parse(readFileSync(new URL(path, root), 'utf8'));
const header = '// DO NOT EDIT — generated by scripts/gen-registry.ts from builtin-inputs.json.\n';
const outputs: Record<string, string> = {};
for (const category of ['effects', 'animations', 'transitions'] as const) {
  const ids = inputs[category];
  const upper = category.slice(0, -1).toUpperCase();
  const contract = category === 'effects' ? 'EffectComponent<never>' : category === 'animations' ? 'AnimationComponent' : 'TransitionComponent';
  const baseContract = contract.split('<')[0];
  const imports = ids.map((id, index) => `import Component${index} from './builtins/${category}/${id}/component';`).join('\n');
  const metadata = Object.fromEntries(ids.map(id => [id, json(`builtins/${category}/${id}/meta.json`)]));
  const defaults = Object.fromEntries(ids.map(id => [id, json(`builtins/${category}/${id}/defaults.json`)]));
  if (category === 'animations') {
    outputs['animation-metadata.generated.ts'] = header
      + `import type {AnimationMeta} from './effects-types';\n`
      + `export const ANIMATION_DEFAULTS: Readonly<Record<string, Record<string, unknown>>> = ${JSON.stringify(defaults, null, 2)};\n`
      + `export const ANIMATION_META: Readonly<Record<string, AnimationMeta>> = ${JSON.stringify(metadata, null, 2)};\n`;
  }
  outputs[`${category}.generated.ts`] = header
    + `import type {${baseContract}${category === 'animations' ? ', AnimationMeta' : ''}} from './effects-types';\n${imports}\n\n`
    + (category === 'animations'
      ? `import {ANIMATION_DEFAULTS as GENERATED_ANIMATION_DEFAULTS, ANIMATION_META as GENERATED_ANIMATION_META} from './animation-metadata.generated';\n`
      : '')
    + `export const ACTIVE_THEME_ID = null;\nexport const ${upper}_IDS = ${JSON.stringify(ids)} as const;\n`
    + `export type ${baseContract.replace('Component', '')}Id = typeof ${upper}_IDS[number];\n`
    + `export const ${upper}_REGISTRY: Readonly<Record<string, ${contract}>> = {\n`
    + ids.map((id, index) => `  '${id}': Component${index},`).join('\n') + '\n};\n'
    + (category === 'animations'
      ? `export const ANIMATION_DEFAULTS = GENERATED_ANIMATION_DEFAULTS;\nexport const ANIMATION_META = GENERATED_ANIMATION_META;\n`
      : `export const ${upper}_DEFAULTS: Readonly<Record<string, Record<string, unknown>>> = ${JSON.stringify(defaults, null, 2)};\n`
        + `export const ${upper}_META: Readonly<Record<string, Record<string, unknown>>> = ${JSON.stringify(metadata, null, 2)};\n`)
    + (category === 'effects' ? `export const CLIP_TYPE_ALIASES: Readonly<Record<string, string>> = ${JSON.stringify(inputs.clipTypeAliases, null, 2)};\n` : '');
}
const themes = inputs.themes.flatMap(theme => theme.effects.map(id => ({...theme, clipType: id})));
outputs['registry.generated.ts'] = header
  + "import type {EffectComponent} from './effects-types';\n"
  + themes.map((theme, index) => `import Component${index} from './builtins/themes/${theme.id}/effects/${theme.clipType}/component';`).join('\n')
  + '\n\nexport type ThemePackageRegistryEntry = {\n  component: EffectComponent<never>;\n  themeId: string;\n  source: string;\n};\n\n'
  + `export const THEME_PACKAGE_CLIP_TYPES = ${JSON.stringify(themes.map(theme => theme.clipType))} as const;\n`
  + 'export type ThemePackageClipType = typeof THEME_PACKAGE_CLIP_TYPES[number];\n'
  + 'export const THEME_PACKAGE_REGISTRY: Readonly<Record<string, ThemePackageRegistryEntry>> = {\n'
  + themes.map((theme, index) => `  '${theme.clipType}': {component: Component${index}, themeId: '${theme.id}', source: 'bundled:${theme.id}@${theme.version}'},`).join('\n') + '\n};\n'
  + `export const THEME_EFFECT_DEFAULTS: Readonly<Record<string, Record<string, unknown>>> = ${JSON.stringify(Object.fromEntries(themes.map(theme => [theme.clipType, json(`builtins/themes/${theme.id}/effects/${theme.clipType}/defaults.json`)])), null, 2)};\n`
  + `export const THEME_EFFECT_META: Readonly<Record<string, Record<string, unknown>>> = ${JSON.stringify(Object.fromEntries(themes.map(theme => [theme.clipType, json(`builtins/themes/${theme.id}/effects/${theme.clipType}/meta.json`)])), null, 2)};\n`
  + `export const BUNDLED_THEME_VERSIONS = ${JSON.stringify(Object.fromEntries(inputs.themes.map(theme => [theme.id, theme.version])))} as const;\n`
  + `export const BUNDLED_THEMES = ${JSON.stringify(Object.fromEntries(inputs.themes.map(theme => {const data = json(`builtins/themes/${theme.id}/theme.json`); return [theme.id, {id: data.id, visual: data.visual}];})), null, 2)};\n`;

let stale = false;
for (const [file, content] of Object.entries(outputs)) {
  const path = new URL(file, root);
  if (process.argv.includes('--check')) {
    if (readFileSync(path, 'utf8') !== content) {
      console.error(`${file} is stale. Run npm run gen-registry.`);
      stale = true;
    }
  } else {
    writeFileSync(path, content);
    console.log(`Wrote ${fileURLToPath(path)}`);
  }
}
if (stale) process.exitCode = 1;
