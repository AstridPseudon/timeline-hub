@pytest.mark.parametrize("member", [
    "entrypoint", "helper.py", "docs/scripts/support.py", "docs/contracts/input.schema.json",
    "docs/assets/required.json", "docs/assets/prompt.md", "resources/prompt.md",
])
def test_executor_digest_binds_consumed_execution_files(execution_closure, member):
    root, entry, definition = execution_closure

    def execute():
        return runpy.run_path(str(entry))["run"]()

    original_result = execute()
    original_digest = executor_definition_digest(definition)
    path = entry if member == "entrypoint" else root / member
    content = path.read_text()
    path.write_text(content.replace("v1", "v2").replace('"maxLength": 10', '"maxLength": 20'))
    assert execute() != original_result  # Every fixture member actually affects execution.
    assert executor_definition_digest(definition) != original_digest


@pytest.mark.parametrize("member", [
    "README.md", "AGENTS.md", "STAGE.md", "docs/SKILL.md", "docs/references/guide.md",
    "docs/setup/guide.rst", ".DS_Store", ".git", ".git/index", ".pytest_cache/v/cache/nodeids",
    ".mypy_cache/module.json", ".ruff_cache/cache", "__pycache__/run.cpython-314.pyc",
])
def test_executor_digest_ignores_documentation_and_generated_debris(execution_closure, member):
    root, entry, definition = execution_closure
    original_result = runpy.run_path(str(entry))["run"]()
    before = executor_definition_digest(definition)
    path = root / member
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("first documentation or generated bytes")
    assert executor_definition_digest(definition) == before
    path.write_text("changed documentation or regenerated bytes")
    assert executor_definition_digest(definition) == before
    assert runpy.run_path(str(entry))["run"]() == original_result
    path.unlink()
    assert executor_definition_digest(definition) == before


@pytest.mark.parametrize("change", ["checkout", "mtime", "bytecode"])
def test_execution_closure_is_portable_and_ignores_file_metadata(execution_closure, tmp_path, change):
    root, entry, definition = execution_closure
    if change == "bytecode":
        py_compile.compile(str(entry), cfile=str(root / "run.pyc"), dfile="before/run.py", doraise=True)
        old_bytecode = (root / "run.pyc").read_bytes()
    before = executor_definition_digest(definition)
    result = runpy.run_path(str(entry))["run"]()
    if change == "checkout":
        moved = tmp_path / "renamed-checkout"
        shutil.copytree(root, moved)
        definition = {**definition, "metadata": {
            key: value.replace(str(root), str(moved)) if isinstance(value, str) else value
            for key, value in definition["metadata"].items()
        }}
        entry = moved / entry.relative_to(root)
    elif change == "mtime":
        for path in root.rglob("*"):
            os.utime(path, (1700000000, 1700000000))
    else:
        py_compile.compile(str(entry), cfile=str(root / "run.pyc"), dfile="after/run.py", doraise=True)
        assert (root / "run.pyc").read_bytes() != old_bytecode
        cache = root / "__pycache__"
        cache.mkdir()
        py_compile.compile(str(entry), cfile=str(cache / "run.test.pyc"), doraise=True)
    assert runpy.run_path(str(entry))["run"]() == result
    assert executor_definition_digest(definition) == before


@pytest.mark.parametrize("reference", ["relative", "absolute", "uri"])
def test_explicitly_declared_prose_resource_remains_in_execution_closure(execution_closure, reference):
    root, entry, definition = execution_closure
    resource = root / "docs/references/required.md"
    resource.parent.mkdir(parents=True)
    resource.write_text("Runtime input v1")
    entry.write_text(entry.read_text() + "\noriginal_run = run\ndef run():\n"
                     "    return [original_run(), (root / 'docs/references/required.md').read_text()]\n")
    value = {"relative": resource.relative_to(root).as_posix(),
             "absolute": str(resource), "uri": resource.as_uri()}[reference]
    definition["command"] = {"argv": ["{python_exec}", str(entry), value]}
    before = executor_definition_digest(definition)
    original = runpy.run_path(str(entry))["run"]()
    resource.write_text("Runtime input v2")
    assert runpy.run_path(str(entry))["run"]() != original
    assert executor_definition_digest(definition) != before


@pytest.mark.parametrize("layout", ["folder", "external_pack"])
@pytest.mark.parametrize("member", [
    "STAGE.md", "README.md", "docs/references/guide.md", "guides/guide.md",
    "assets/.DS_Store", "assets/__pycache__/helper.pyc", "guides/__pycache__/helper.pyc",
])
def test_discovery_inventories_do_not_reintroduce_nonexecution_files(tmp_path, layout, member):
    from astrid.core.execution.generic_host import GenericPackHost
    from tests.test_generic_host import _write_manifest

    root = tmp_path / "fixture_provider"
    folder = root / "executors/echo" if layout == "external_pack" else root
    _write_manifest(folder, capability_id="fixture_provider.echo")
    if layout == "external_pack":
        (root / "pack.yaml").write_text(json.dumps({"schema_version": 1,
            "id": "fixture_provider", "name": "Fixture", "version": "1.0",
            "capabilities": ["echo"], "content": {"executors": "executors"}}))

    def digest():
        return GenericPackHost(pack_roots=[root]).discover()[0].capability_digest

    before = digest()
    path = folder / member
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("first documentation or generated bytes")
    assert digest() == before
    path.write_text("changed documentation or regenerated bytes")
    assert digest() == before
    path.unlink()
    assert digest() == before


