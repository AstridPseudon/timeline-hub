#!/bin/sh
set -eu

HERE=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
. "$HERE/normal014-source-common.sh"

mode=${1:-preflight}
run_root=${NORMAL014_RUN_ROOT:-$(mktemp -d /tmp/timeline-normal014-parent.XXXXXX)}
cleanup=1
if [ "${NORMAL014_KEEP_TEMP:-0}" = 1 ]; then cleanup=0; fi
trap '[ "$cleanup" = 1 ] && rm -rf "$run_root"' EXIT HUP INT TERM

case "$mode" in
  preflight|run) ;;
  *) echo "usage: $0 preflight|run" >&2; exit 2;;
esac

prepare_sources "$run_root/sources"
runtime="$run_root/sources/runtime-202"
agent="$run_root/sources/agent-3c4"
verify_locked_graph
prepare_private_python "$run_root"

# The marker is test-only and comes from d05e.  It is deliberately overlaid on
# the private 202 checkout: the accepted positive is still run with --runxfail
# against 202's schema.  No schema, artifact, producer, or generated byte is
# changed.  The current-013 refusal is never relabelled as 202 evidence.
git -C "$runtime" show "$D05E_SHA:tests/test_timeline_clip_replacement.py" > "$runtime/tests/test_timeline_clip_replacement.py"
test "$(git -C "$runtime" hash-object "$runtime/tests/test_timeline_clip_replacement.py")" = "$MARKER_SHA"
grep -F "test_native_parent_clip_swap_route_refuses_parent_ownership_on_current_schema" "$runtime/tests/test_timeline_clip_replacement.py" >/dev/null
grep -F "test_native_parent_clip_swap_route_replaces_parent_media" "$runtime/tests/test_timeline_clip_replacement.py" >/dev/null
verify_python_imports_and_collection "$NORMAL014_PYTHON" "$agent" "$runtime"
for tool in ffmpeg ffprobe; do
  command -v "$tool" >/dev/null
  "$tool" -version >/dev/null 2>&1
done

if [ "$mode" = preflight ]; then
  echo "normal014 parent-media preflight: source tuple, d05e marker, locked graph, and shell guards verified"
  exit 0
fi

cd "$runtime"
export ASTRID_CHECKOUT="$agent"
export ASTRID_RUNTIME_CHECKOUT="$runtime"
export PYTHONDONTWRITEBYTECODE=1
export PYTHONPATH="$agent:$runtime"
export PYTHONNOUSERSITE=1
export PIP_CACHE_DIR="$run_root/pip-cache"
exec "$NORMAL014_PYTHON" -m pytest -q -c /dev/null -p no:cacheprovider --runxfail \
  tests/test_timeline_clip_replacement.py::test_native_parent_clip_swap_route_replaces_parent_media
